/// Host entity of a reactive region. With the `ui` feature it is a
/// `GhostNode`, so its children are laid out as children of its parent.
#[doc(hidden)]
#[derive(Component, Clone, Copy, Debug, Default)]
#[cfg_attr(feature = "ui", require(bevy::ui::experimental::GhostNode))]
#[cfg_attr(feature = "ui", component(on_add = strip_ghost_transform))]
pub struct Region;

type BoxedList = Box<dyn SceneList>;

fn spawn_list(world: &mut World, parent: Entity, list: BoxedList) -> Vec<Entity> {
    match world.spawn_scene_list(list) {
        Ok(entities) => {
            for &entity in &entities {
                world.entity_mut(entity).insert(ChildOf(parent));
            }
            entities
        }
        Err(error) => {
            let handler = world.fallback_error_handler();
            handler(
                BevyError::from(error),
                bevy::ecs::error::ErrorContext::Command {
                    name: "bevy_radioactive::view::spawn".into(),
                },
            );
            Vec::new()
        }
    }
}

fn despawn_all(world: &mut World, entities: &[Entity]) {
    for &entity in entities {
        world.despawn(entity);
    }
}

/// Patches component `C` whenever a signal read by `f` changes.
#[doc(hidden)]
pub fn patch<C, F>(f: F) -> impl Template<Output = EmptySceneEffect>
where
    C: Component<Mutability = Mutable>,
    F: Fn(&mut C) + Clone + Send + Sync + 'static,
{
    effect_template(move || -> RunFn {
        let f = f.clone();
        Box::new(move |world: &mut World, target| {
            let ((), signals) = scope(|| {
                if let Some(mut component) = world.get_mut::<C>(target) {
                    f(&mut component);
                }
            });
            signals
        })
    })
}

/// Rebuilds the region's children whenever `key()` changes.
#[doc(hidden)]
pub fn region<K, KF, R>(key: KF, render: R) -> impl Template<Output = EmptySceneEffect>
where
    K: PartialEq + Send + Sync + 'static,
    KF: Fn() -> K + Clone + Send + Sync + 'static,
    R: Fn(&K) -> Option<BoxedList> + Clone + Send + Sync + 'static,
{
    effect_template(move || -> RunFn {
        let (key, render) = (key.clone(), render.clone());
        let mut current: Option<(K, Vec<Entity>)> = None;
        Box::new(move |world: &mut World, target| {
            let (next, deps) = scope(&key);
            if current.as_ref().is_none_or(|(key, _)| *key != next) {
                if let Some((_, children)) = current.take() {
                    despawn_all(world, &children);
                }
                let children = untracked(|| render(&next))
                    .map(|list| spawn_list(world, target, list))
                    .unwrap_or_default();
                current = Some((next, children));
            }
            deps
        })
    })
}

/// Keeps one set of children per item, reusing unchanged rows.
#[doc(hidden)]
pub fn for_keyed<V, K, IF, KF, R>(
    items: IF,
    key: KF,
    render: R,
) -> impl Template<Output = EmptySceneEffect>
where
    V: PartialEq + Send + Sync + 'static,
    K: Eq + Hash + Send + Sync + 'static,
    IF: Fn() -> Vec<V> + Clone + Send + Sync + 'static,
    KF: Fn(&V) -> K + Clone + Send + Sync + 'static,
    R: Fn(&V) -> BoxedList + Clone + Send + Sync + 'static,
{
    keyed_rows(
        items,
        key,
        |item| item,
        |row: &V, item| (*row != item).then_some(item),
        render,
    )
}

/// Like [`for_keyed`], but each row gets its item as a signal: a changed
/// item is written to the row's signal instead of rebuilding the row.
#[doc(hidden)]
pub fn for_keyed_signal<V, K, IF, KF, R>(
    items: IF,
    key: KF,
    render: R,
) -> impl Template<Output = EmptySceneEffect>
where
    V: PartialEq + Send + Sync + 'static,
    K: Eq + Hash + Send + Sync + 'static,
    IF: Fn() -> Vec<V> + Clone + Send + Sync + 'static,
    KF: Fn(&V) -> K + Clone + Send + Sync + 'static,
    R: Fn(&Signal<V>) -> BoxedList + Clone + Send + Sync + 'static,
{
    keyed_rows(
        items,
        key,
        Signal::new,
        |row: &Signal<V>, item| {
            row.set_if_neq(item);
            None
        },
        render,
    )
}

/// One set of children per key. `reuse` updates a kept row from its new
/// item, or hands the item back to rebuild the row with `make`.
fn keyed_rows<V, S, K, IF, KF, R>(
    items: IF,
    key: KF,
    make: fn(V) -> S,
    reuse: fn(&S, V) -> Option<V>,
    render: R,
) -> impl Template<Output = EmptySceneEffect>
where
    V: Send + Sync + 'static,
    S: Send + Sync + 'static,
    K: Eq + Hash + Send + Sync + 'static,
    IF: Fn() -> Vec<V> + Clone + Send + Sync + 'static,
    KF: Fn(&V) -> K + Clone + Send + Sync + 'static,
    R: Fn(&S) -> BoxedList + Clone + Send + Sync + 'static,
{
    effect_template(move || -> RunFn {
        let (items, key, render) = (items.clone(), key.clone(), render.clone());
        let mut rows: HashMap<K, (S, Vec<Entity>)> = HashMap::default();
        let mut order: Vec<Entity> = Vec::new();
        Box::new(move |world: &mut World, target| {
            let (next, deps) = scope(&items);
            let mut next_rows: HashMap<K, (S, Vec<Entity>)> = HashMap::default();
            let mut next_order = Vec::new();
            let mut duplicates = 0;
            for item in next {
                let item_key = untracked(|| key(&item));
                let rebuild = match rows.remove(&item_key) {
                    Some((row, children)) => match reuse(&row, item) {
                        None => Ok((row, children)),
                        Some(item) => {
                            despawn_all(world, &children);
                            Err(item)
                        }
                    },
                    None => Err(item),
                };
                let (row, children) = rebuild.unwrap_or_else(|item| {
                    let row = make(item);
                    let children = spawn_list(world, target, untracked(|| render(&row)));
                    (row, children)
                });
                next_order.extend(children.iter().copied());
                if let Some((_, displaced)) = next_rows.insert(item_key, (row, children)) {
                    // A duplicate key: the later item wins and the earlier
                    // row is despawned rather than left untracked.
                    duplicates += 1;
                    next_order.retain(|entity| !displaced.contains(entity));
                    despawn_all(world, &displaced);
                }
            }
            if duplicates > 0 {
                warn!(
                    "view: {duplicates} duplicate key(s) in a keyed `for`; only the last item \
                     with each key is shown"
                );
            }
            for (_, (_, children)) in rows.drain() {
                despawn_all(world, &children);
            }
            rows = next_rows;
            if next_order != order
                && let Ok(mut entity) = world.get_entity_mut(target)
            {
                entity.replace_children(&next_order);
            }
            order = next_order;
            deps
        })
    })
}

#[doc(hidden)]
pub fn for_indexed<V, IF, R>(items: IF, render: R) -> impl Template<Output = EmptySceneEffect>
where
    V: PartialEq + Send + Sync + 'static,
    IF: Fn() -> Vec<V> + Clone + Send + Sync + 'static,
    R: Fn(&V) -> BoxedList + Clone + Send + Sync + 'static,
{
    for_keyed(
        move || items().into_iter().enumerate().collect::<Vec<_>>(),
        |(index, _): &(usize, V)| *index,
        move |(_, item): &(usize, V)| render(item),
    )
}

/// Like [`for_indexed`], but each position keeps its row and gets its item
/// as a signal.
#[doc(hidden)]
pub fn for_indexed_signal<V, IF, R>(
    items: IF,
    render: R,
) -> impl Template<Output = EmptySceneEffect>
where
    V: PartialEq + Send + Sync + 'static,
    IF: Fn() -> Vec<V> + Clone + Send + Sync + 'static,
    R: Fn(&Signal<V>) -> BoxedList + Clone + Send + Sync + 'static,
{
    effect_template(move || -> RunFn {
        let (items, render) = (items.clone(), render.clone());
        let mut rows: Vec<(Signal<V>, Vec<Entity>)> = Vec::new();
        Box::new(move |world: &mut World, target| {
            let (next, deps) = scope(&items);
            let len = next.len();
            for (index, item) in next.into_iter().enumerate() {
                if let Some((signal, _)) = rows.get(index) {
                    signal.set_if_neq(item);
                } else {
                    let signal = Signal::new(item);
                    let children = spawn_list(world, target, untracked(|| render(&signal)));
                    rows.push((signal, children));
                }
            }
            for (_, children) in rows.drain(len.min(rows.len())..) {
                despawn_all(world, &children);
            }
            deps
        })
    })
}

