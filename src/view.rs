trait Versioned: Send + Sync {
    fn version(&self) -> u64;
}

/// A watched value read by a tracking scope, with the version it had.
#[derive(Clone)]
struct Dep {
    source: Arc<dyn Versioned>,
    version: u64,
}

impl Dep {
    fn is_dirty(&self) -> bool {
        self.source.version() != self.version
    }
}

thread_local! {
    static SCOPES: RefCell<Vec<Vec<Dep>>> = const { RefCell::new(Vec::new()) };
}

struct ScopeGuard;

impl Drop for ScopeGuard {
    fn drop(&mut self) {
        SCOPES.with(|scopes| scopes.borrow_mut().pop());
    }
}

/// Runs `f`, collecting every watched value it reads.
fn scope<R>(f: impl FnOnce() -> R) -> (R, Vec<Dep>) {
    SCOPES.with(|scopes| scopes.borrow_mut().push(Vec::new()));
    let guard = ScopeGuard;
    let value = f();
    let deps = SCOPES.with(|scopes| scopes.borrow_mut().last_mut().map(std::mem::take));
    drop(guard);
    (value, deps.unwrap_or_default())
}

fn record(source: Arc<dyn Versioned>) {
    let version = source.version();
    SCOPES.with(|scopes| {
        if let Some(scope) = scopes.borrow_mut().last_mut() {
            scope.push(Dep { source, version });
        }
    });
}

fn untracked<R>(f: impl FnOnce() -> R) -> R {
    scope(f).0
}

