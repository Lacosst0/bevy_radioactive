/// A shared, versioned value. Reads inside a tracking scope record it.
#[doc(hidden)]
pub struct Cell<V> {
    value: RwLock<Option<V>>,
    version: AtomicU64,
}

impl<V: Send + Sync> Versioned for Cell<V> {
    fn version(&self) -> u64 {
        self.version.load(Ordering::Acquire)
    }
}

impl<V: Send + Sync + 'static> Cell<V> {
    fn new(value: Option<V>) -> Arc<Self> {
        Arc::new(Self {
            value: RwLock::new(value),
            version: AtomicU64::new(0),
        })
    }

    fn write<R>(&self, f: impl FnOnce(&mut Option<V>) -> R) -> R {
        let result = f(&mut self.value.write().unwrap_or_else(PoisonError::into_inner));
        self.version.fetch_add(1, Ordering::AcqRel);
        result
    }
}

/// Where a [`Watch`] gets its value from: [`Local`] state of one component
/// instance, or a resource through [`Res`] or `Option<Res>`.
pub trait WatchParam {
    /// The value a [`Watch`] of this parameter reads.
    type Value: Send + Sync + 'static;

    #[doc(hidden)]
    fn source() -> Source<Self::Value>;
}

#[doc(hidden)]
pub enum Source<V> {
    /// Owned by the watch.
    Local(V),
    /// Bound to a shared cell in the world when the scene spawns.
    World(fn(&mut World) -> Arc<Cell<V>>),
}

/// Per-instance state of a view component, starting at `T::default()`, or
/// at `#[init(value)]` on the parameter. Writable with
/// [`set`](Watch::set) and [`update`](Watch::update).
impl<T: FromWorld + Default + Send + Sync + 'static> WatchParam for Local<'_, T> {
    type Value = T;

    fn source() -> Source<T> {
        Source::Local(T::default())
    }
}

/// Resource `T`. Reading it while the resource doesn't exist panics; use
/// `Watch<Option<Res<T>>>` for resources that may be missing.
impl<T: Resource + Clone> WatchParam for Res<'_, T> {
    type Value = T;

    #[expect(
        clippy::redundant_closure_for_method_calls,
        reason = "`Option::cloned` is ambiguous between `&T` and `&mut T`"
    )]
    fn source() -> Source<T> {
        Source::World(|world| bind_resource::<T, T>(world, |value| value.cloned()))
    }
}

/// Resource `T`, or `None` while it doesn't exist.
impl<T: Resource + Clone> WatchParam for Option<Res<'_, T>> {
    type Value = Option<T>;

    fn source() -> Source<Option<T>> {
        Source::World(|world| bind_resource::<T, Option<T>>(world, |value| Some(value.cloned())))
    }
}

/// A value a [`view!`] template reacts to, declared as a parameter of a
/// [`#[component]`](component) function. The parameter's type says where the
/// value comes from:
///
/// ```ignore
/// #[component]
/// fn counter(count: Watch<Local<i32>>, theme: Watch<Res<Theme>>) -> impl Scene {
///     view! {
///         Button
///         on(move |_: On<Pointer<Click>>| count.set($count + 1))
///         Children [ Text($(format!("{} ({:?})", $count, $theme.mode))) ]
///     }
/// }
/// ```
///
/// `$name` in [`view!`] reads it. Regions, patched components and
/// [`effect`]s that read it run again when it changes: when it is
/// [`set`](Self::set) for [`Local`] state, or when the resource changes for
/// [`Res`]. Cloning is cheap and every clone refers to the same value.
pub struct Watch<P: WatchParam> {
    inner: Arc<WatchInner<P::Value>>,
    marker: PhantomData<fn() -> P>,
}

struct WatchInner<V> {
    cell: OnceLock<Arc<Cell<V>>>,
    bind: Option<fn(&mut World) -> Arc<Cell<V>>>,
}

impl<P: WatchParam> Watch<P> {
    #[doc(hidden)]
    #[must_use]
    pub fn __new() -> Self {
        let inner = match P::source() {
            Source::Local(value) => WatchInner {
                cell: OnceLock::from(Cell::new(Some(value))),
                bind: None,
            },
            Source::World(bind) => WatchInner {
                cell: OnceLock::new(),
                bind: Some(bind),
            },
        };
        Self {
            inner: Arc::new(inner),
            marker: PhantomData,
        }
    }

    fn cell(&self) -> &Arc<Cell<P::Value>> {
        self.inner.cell.get().unwrap_or_else(|| {
            panic!(
                "`Watch<{}>` was read before its scene spawned; read it with `$` in a \
                 component field, region or handler instead of a `{{ }}` value",
                std::any::type_name::<P>(),
            )
        })
    }

    /// Reads the value through `f` and tracks the read.
    pub fn with<R>(&self, f: impl FnOnce(&P::Value) -> R) -> R {
        record(self.cell().clone());
        self.with_untracked(f)
    }

    /// Reads the value through `f` without tracking.
    ///
    /// # Panics
    ///
    /// For `Watch<Res<T>>`, if the resource doesn't exist.
    pub fn with_untracked<R>(&self, f: impl FnOnce(&P::Value) -> R) -> R {
        let value = self
            .cell()
            .value
            .read()
            .unwrap_or_else(PoisonError::into_inner);
        f(value.as_ref().unwrap_or_else(|| {
            panic!(
                "`Watch<{}>` read a missing resource; use `Watch<Option<Res<..>>>`",
                std::any::type_name::<P>(),
            )
        }))
    }

    /// Clones the value and tracks the read.
    #[must_use]
    pub fn get(&self) -> P::Value
    where
        P::Value: Clone,
    {
        self.with(P::Value::clone)
    }

    /// Clones the value without tracking.
    #[must_use]
    pub fn get_untracked(&self) -> P::Value
    where
        P::Value: Clone,
    {
        self.with_untracked(P::Value::clone)
    }
}

impl<T: FromWorld + Default + Send + Sync + 'static> Watch<Local<'_, T>> {
    /// Local state starting at `value`.
    #[must_use]
    pub fn new(value: T) -> Self {
        let watch = Self::__new();
        watch.cell().write(|current| *current = Some(value));
        watch
    }

    /// Replaces the value and notifies readers.
    pub fn set(&self, value: T) {
        self.update(|current| *current = value);
    }

    /// Replaces the value, notifying readers only if it changed.
    ///
    /// Returns whether the value changed.
    pub fn set_if_neq(&self, value: T) -> bool
    where
        T: PartialEq,
    {
        if self.with_untracked(|current| *current == value) {
            return false;
        }
        self.set(value);
        true
    }

    /// Mutates the value in place and notifies readers.
    ///
    /// # Panics
    ///
    /// Never: local state always holds a value.
    pub fn update<R>(&self, f: impl FnOnce(&mut T) -> R) -> R {
        self.cell()
            .write(|value| f(value.as_mut().expect("local state holds a value")))
    }
}

impl<T: FromWorld + Default + Send + Sync + 'static> Default for Watch<Local<'_, T>> {
    fn default() -> Self {
        Self::__new()
    }
}

impl<P: WatchParam> Clone for Watch<P> {
    fn clone(&self) -> Self {
        Self {
            inner: Arc::clone(&self.inner),
            marker: PhantomData,
        }
    }
}

impl<P: WatchParam> fmt::Debug for Watch<P>
where
    P::Value: fmt::Debug,
{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut tuple = f.debug_tuple("Watch");
        match self.inner.cell.get() {
            Some(cell) => tuple.field(&*cell.value.read().unwrap_or_else(PoisonError::into_inner)),
            None => tuple.field(&"<unbound>"),
        };
        tuple.finish()
    }
}

/// Resource cells shared by every watch of a world, refreshed each round.
#[derive(Resource, Default)]
struct WatchedResources {
    cells: HashMap<TypeId, Box<dyn Any + Send + Sync>>,
    syncs: Vec<Box<dyn FnMut(&World) + Send + Sync>>,
}

/// Returns the world's shared cell for resource `T` read as `V`, creating it.
fn bind_resource<T: Resource, V: Send + Sync + 'static>(
    world: &mut World,
    read: fn(Option<&T>) -> Option<V>,
) -> Arc<Cell<V>> {
    let key = TypeId::of::<(T, V)>();
    let mut resources = world.resource_mut::<WatchedResources>();
    if let Some(cell) = resources
        .cells
        .get(&key)
        .and_then(|cell| cell.downcast_ref::<Arc<Cell<V>>>())
    {
        return cell.clone();
    }
    let cell = Cell::new(None);
    resources.cells.insert(key, Box::new(cell.clone()));
    let shared = cell.clone();
    let mut last = None;
    let mut sync = move |world: &World| {
        let tick = world
            .get_resource_change_ticks::<T>()
            .map(|ticks| ticks.changed.get());
        if last != Some(tick) {
            last = Some(tick);
            let value = read(world.get_resource::<T>());
            shared.write(|current| *current = value);
        }
    };
    sync(world);
    world
        .resource_mut::<WatchedResources>()
        .syncs
        .push(Box::new(sync));
    cell
}

fn sync_resources(world: &mut World) {
    let mut syncs = std::mem::take(&mut world.resource_mut::<WatchedResources>().syncs);
    for sync in &mut syncs {
        sync(world);
    }
    let mut resources = world.resource_mut::<WatchedResources>();
    syncs.append(&mut resources.syncs);
    resources.syncs = syncs;
}

/// A [`Watch`] with its parameter erased, for binding.
#[doc(hidden)]
pub trait Bindable: Send + Sync + 'static {
    fn bind(&self, world: &mut World);
}

impl<V: Send + Sync + 'static> Bindable for WatchInner<V> {
    fn bind(&self, world: &mut World) {
        if let Some(bind) = self.bind
            && self.cell.get().is_none()
        {
            let _ = self.cell.set(bind(world));
        }
    }
}

/// The binding a [`#[component]`](component) function needs for `watch`, if
/// any.
#[doc(hidden)]
#[must_use]
pub fn binding<P: WatchParam>(watch: &Watch<P>) -> Option<Arc<dyn Bindable>> {
    watch
        .inner
        .bind
        .is_some()
        .then(|| watch.inner.clone() as Arc<dyn Bindable>)
}

/// A component's scene, plus the resource watches to bind when it spawns.
#[doc(hidden)]
pub struct Bound<S> {
    watches: Vec<Arc<dyn Bindable>>,
    scene: S,
}

#[doc(hidden)]
pub fn bound<S>(
    watches: impl IntoIterator<Item = Option<Arc<dyn Bindable>>>,
    scene: S,
) -> Bound<S> {
    Bound {
        watches: watches.into_iter().flatten().collect(),
        scene,
    }
}

struct BindTemplate(Vec<Arc<dyn Bindable>>);

impl Template for BindTemplate {
    type Output = EmptySceneEffect;

    fn build_template(&self, context: &mut TemplateContext) -> Result<EmptySceneEffect> {
        context.entity.world_scope(|world| {
            if !world.contains_resource::<WatchedResources>() {
                return Err("`Watch` needs `ViewPlugin`; add it to the app".to_string());
            }
            for watch in &self.0 {
                watch.bind(world);
            }
            Ok(())
        })?;
        Ok(EmptySceneEffect)
    }

    fn clone_template(&self) -> Self {
        Self(self.0.clone())
    }
}

impl<S: Scene> Scene for Bound<S> {
    fn resolve(
        self,
        context: &mut ResolveContext,
        scene: &mut ResolvedScene,
    ) -> Result<(), ResolveSceneError> {
        if !self.watches.is_empty() {
            scene.push_template(BindTemplate(self.watches));
        }
        self.scene.resolve(context, scene)
    }

    fn register_dependencies(&self, dependencies: &mut SceneDependencies) {
        self.scene.register_dependencies(dependencies);
    }
}

impl<L: SceneList> SceneList for Bound<L> {
    fn resolve_list(
        self,
        context: &mut ResolveContext,
        scenes: &mut Vec<ResolvedScene>,
    ) -> Result<(), ResolveSceneError> {
        let first = scenes.len();
        self.scene.resolve_list(context, scenes)?;
        if !self.watches.is_empty()
            && let Some(scene) = scenes.get_mut(first)
        {
            scene.push_template(BindTemplate(self.watches));
        }
        Ok(())
    }

    fn register_dependencies(&self, dependencies: &mut SceneDependencies) {
        self.scene.register_dependencies(dependencies);
    }
}

