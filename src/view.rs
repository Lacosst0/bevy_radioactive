//! Fine-grained reactive templates: [`view!`] is `bsn!` plus reactive
//! control flow, modelled on [Topcoat](https://github.com/tokio-rs/topcoat).
//! What a template reacts to is declared in the type of its component's
//! parameters.
//!
//! ```ignore
//! use bevy_radioactive::view::*;
//!
//! app.add_plugins(ViewPlugin);
//!
//! #[derive(Resource, Clone, Default)]
//! struct Todos(Vec<Todo>);
//!
//! #[component]
//! fn todo_list(todos: Watch<Res<Todos>>, open: Watch<Local<bool>>) -> impl Scene {
//!     view! {
//!         Node
//!         Children [
//!             Button
//!             on(move |_: On<Pointer<Click>>| open.set(!$open))
//!             --
//!             // patched in place when `Todos` changes
//!             Text($(format!("{} todos", $todos.0.len())))
//!             --
//!             // rebuilt only when the condition changes
//!             if $open {
//!                 // keyed: unchanged rows keep their entities
//!                 #[key(todo.id)]
//!                 for todo in $todos.0 { Text({todo.title.clone()}) }
//!             } else {
//!                 Text("hidden")
//!             }
//!         ]
//!     }
//! }
//!
//! // bsn! { @todo_list() }
//! ```
//!
//! # Components
//!
//! [`#[component]`](component) turns a function returning a scene into one
//! used like a scene function, `@todo_list()`. Each [`Watch`] parameter is
//! created by the runtime and its type says where the value comes from:
//!
//! | Parameter | Value |
//! | --- | --- |
//! | `Watch<Local<T>>` | state of this instance, starting at `T::default()`; writable with `set`/`update` |
//! | `#[init(expr)] Watch<Local<T>>` | same, starting at `expr` (other parameters are in scope) |
//! | `Watch<Res<T>>` | resource `T`, read-only; follows the resource's change detection |
//! | `Watch<Option<Res<T>>>` | resource `T`, or `None` while it doesn't exist |
//!
//! Other parameters are props: `@row(todo)` passes `todo`.
//!
//! # Template language
//!
//! `view!` accepts everything `bsn!` accepts. Inside relationship lists
//! (`Children [ ... ]`) an item may also be:
//!
//! | Item | Meaning |
//! | --- | --- |
//! | `if c { .. } else if c { .. } else { .. }` | conditional entities |
//! | `#[key(expr)] for pat in iter { .. }` | entities per item; unchanged rows keep their entities |
//! | `for pat in iter { .. }` | entities per item, identified by position |
//! | `match value { pat => .., }` | entities for the matching arm |
//! | `let pat = expr;` | binding for the following items |
//!
//! `$name` reads watch `name`, and `$(expr)` groups an expression. Control
//! flow that reads a watch becomes a *region* that rebuilds only itself when
//! the value changes (a `GhostNode` with the `ui` feature, so it doesn't
//! affect layout). Without `$` it is evaluated once. A component with `$` in
//! its fields, such as `Text($(format!("{}", $count)))`, is patched in place,
//! starting before the first UI layout. Closures generated by the macro clone
//! the watches they use, so one watch can be used anywhere in the template.
//!
//! Updates run in [`ViewSystems`] in `PostUpdate`, before UI layout. Resource
//! watches pick up changes made before that set in the same frame.

